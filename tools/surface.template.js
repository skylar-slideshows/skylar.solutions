/* Interactive control surface for the controls page: the four channel strips seen from above.
   Generated by tools/build-surface.py from tools/surface.template.js (the geometry below comes
   from the faceplate DXF). The LED rings follow the firmware: led_driver.c's led_render() and
   knob_control.c's encoder steps. */
(function () {
  "use strict";
  var DATA = /*DATA*/null;
  var NS = "http://www.w3.org/2000/svg";
  var LEDS = 32, CENTER = 16, U_MAX = 65535, S_MAX = 32767;
  var STEP = Math.floor(S_MAX / 32);          // one detent; half while the knob's switch is held (Shift)
  var FIRST_ANGLE = 225.13, LED_PITCH = 8.4716, LED_RADIUS = 7.6;   // D1 at ~7:30, clockwise
  var PX_PER_DETENT = 5, WHEEL_PER_DETENT = 40;
  // per strip, top to bottom: cap colour, ring scale, default value, name
  var KNOBS = [
    ["#d62b30", "left", 20480, "red knob, input gain"],      // 10 LEDs: up to 10 o'clock
    ["#f08022", "center", 0, "upper orange knob"],
    ["#f08022", "left", 32767, "lower orange knob"],          // left half: up to 12 o'clock
    ["#f5c62c", "center", 0, "upper yellow knob"],
    ["#f5c62c", "left", 32767, "lower yellow knob"],
    ["#40a854", "center", 0, "upper green knob"],
    ["#40a854", "left", 32767, "lower green knob"],
    ["#3470d6", "center", 0, "upper blue knob"],
    ["#3470d6", "left", 32767, "lower blue knob"],
    ["#844acc", "center", 0, "purple knob, pan"]
  ];

  // led_driver.c: value out of full -> 0..span LEDs, rounded to nearest
  function frac(value, full, span) {
    if (span === 0) return 0;
    if (value >= full) return span;
    return Math.floor((value * span + Math.floor(full / 2)) / full);
  }

  // led_render(): which of the 32 LEDs are lit for a value
  function litLeds(scale, value) {
    var on = [], i, n;
    for (i = 0; i < LEDS; i++) on.push(false);
    if (scale === "left") {
      n = frac(value, U_MAX, LEDS);                           // 0 = all dark
      for (i = 0; i < n; i++) on[i] = true;
    } else if (value >= 0) {
      n = frac(value, S_MAX, LEDS - 1 - CENTER);              // the centre LED is always lit
      for (i = CENTER; i <= CENTER + n; i++) on[i] = true;
    } else {
      n = frac(-value, S_MAX + 1, CENTER);
      for (i = CENTER - n; i <= CENTER; i++) on[i] = true;
    }
    return on;
  }

  function el(name, attrs, parent) {
    var e = document.createElementNS(NS, name);
    for (var k in attrs) if (Object.prototype.hasOwnProperty.call(attrs, k) && attrs[k] !== null) e.setAttribute(k, attrs[k]);
    if (parent) parent.appendChild(e);
    return e;
  }

  function defs(svg) {
    var d = el("defs", {}, svg);
    var cap = el("radialGradient", { id: "sf-cap-shine", cx: "0.36", cy: "0.3", r: "0.8" }, d);
    el("stop", { offset: "0", "stop-color": "#fff", "stop-opacity": "0.45" }, cap);
    el("stop", { offset: "0.55", "stop-color": "#fff", "stop-opacity": "0" }, cap);
    el("stop", { offset: "1", "stop-color": "#000", "stop-opacity": "0.25" }, cap);
    var glow = el("radialGradient", { id: "sf-glow" }, d);
    el("stop", { offset: "0", "stop-color": "#fff4dc", "stop-opacity": "0.9" }, glow);
    el("stop", { offset: "1", "stop-color": "#fff4dc", "stop-opacity": "0" }, glow);
    // frosted resin in the ring slits: LEDs blur inside the slit, with a little light spilling out
    var frost = el("filter", { id: "sf-frost", x: "-20%", y: "-20%", width: "140%", height: "140%" }, d);
    el("feGaussianBlur", { stdDeviation: "0.26" }, frost);
    var bloom = el("filter", { id: "sf-bloom", x: "-30%", y: "-30%", width: "160%", height: "160%" }, d);
    el("feGaussianBlur", { stdDeviation: "0.9" }, bloom);
    DATA.rings.forEach(function (ring, k) {
      var c = el("clipPath", { id: "sf-slit-" + k }, d);
      el("path", { d: ring }, c);
    });
    var fader = el("linearGradient", { id: "sf-fader", x1: "0", y1: "0", x2: "0", y2: "1" }, d);
    [["0", "#eceef2"], ["0.12", "#c9ccd2"], ["0.5", "#8f939b"], ["0.88", "#c9ccd2"], ["1", "#eceef2"]].forEach(function (s) {
      el("stop", { offset: s[0], "stop-color": s[1] }, fader);
    });
  }

  function addKnob(g, strip, k, cx, cy, all) {
    var spec = KNOBS[k];
    var state = { scale: spec[1], def: spec[2], value: spec[2], turns: 0 };
    var ring = el("g", {}, g);
    el("path", { d: DATA.rings[k], "class": "sf-window" }, ring);
    var spill = el("g", { filter: "url(#sf-bloom)", "class": "sf-spill" }, ring);           // light on the panel
    var lit = el("g", { "clip-path": "url(#sf-slit-" + k + ")" }, ring);
    var blur = el("g", { filter: "url(#sf-frost)" }, lit);                                   // LEDs under the resin
    var leds = [];
    for (var i = 0; i < LEDS; i++) {
      var a = (FIRST_ANGLE - LED_PITCH * i) * Math.PI / 180;
      var x = (cx + LED_RADIUS * Math.cos(a)).toFixed(2), y = (cy - LED_RADIUS * Math.sin(a)).toFixed(2);
      leds.push([el("circle", { cx: x, cy: y, r: "0.75", "class": "sf-glow" }, spill),
                 el("circle", { cx: x, cy: y, r: "0.45", "class": "sf-led" }, blur)]);
    }
    el("path", { d: DATA.rings[k], "class": "sf-resin" }, ring);                            // the frosted surface
    var min = state.scale === "left" ? 0 : -S_MAX - 1, max = state.scale === "left" ? U_MAX : S_MAX;
    var knob = el("g", {
      "class": "sf-knob", tabindex: "0", role: "slider",
      "aria-label": "Channel " + (strip + 1) + ", " + spec[3],
      "aria-valuemin": String(min), "aria-valuemax": String(max),
      transform: "translate(" + cx + " " + cy + ")"
    }, g);
    el("circle", { r: "5.6", "class": "sf-focus" }, knob);
    el("circle", { cx: "0.35", cy: "0.7", r: "5.05", "class": "sf-shadow" }, knob);
    el("circle", { r: "4.93", "class": "sf-body" }, knob);
    var flutes = el("g", {}, knob);
    for (i = 0; i < 16; i++) {
      var t = i * Math.PI / 8;
      el("line", { x1: (4.5 * Math.cos(t)).toFixed(2), y1: (4.5 * Math.sin(t)).toFixed(2),
                   x2: (4.93 * Math.cos(t)).toFixed(2), y2: (4.93 * Math.sin(t)).toFixed(2), "class": "sf-flute" }, flutes);
    }
    el("circle", { r: "4.46", "class": "sf-rim" }, knob);
    el("circle", { r: "3.91", fill: spec[0] }, knob);
    el("circle", { r: "3.91", fill: "url(#sf-cap-shine)" }, knob);

    function render() {
      var on = litLeds(state.scale, state.value);
      for (var i = 0; i < LEDS; i++) {
        leds[i][0].setAttribute("class", on[i] ? "sf-glow is-on" : "sf-glow");
        leds[i][1].setAttribute("class", on[i] ? "sf-led is-on" : "sf-led");
      }
      flutes.setAttribute("transform", "rotate(" + (state.turns * 15) + ")");   // 24 detents a turn
      knob.setAttribute("aria-valuenow", String(state.value));
      var text;
      if (state.scale === "left") text = Math.round(state.value / U_MAX * 100) + "%";
      else if (state.value === 0) text = "centre";
      else text = (state.value > 0 ? "+" : "\u2212") + Math.round(Math.abs(state.value) / (state.value > 0 ? S_MAX : S_MAX + 1) * 100) + "%";
      knob.setAttribute("aria-valuetext", text);
    }
    function turn(dir, fine) {
      state.turns += dir;
      state.value = Math.max(min, Math.min(max, state.value + dir * (fine ? Math.floor(STEP / 2) : STEP)));
      render();
    }
    function reset() { state.value = state.def; render(); }
    all.push(reset);

    // drag up or down to turn; double-click or double-tap to reset
    var drag = null, lastTap = 0;
    knob.addEventListener("pointerdown", function (e) {
      if (e.pointerType === "mouse" && e.button !== 0) return;
      e.preventDefault();
      knob.setPointerCapture(e.pointerId);
      if (knob.focus) { try { knob.focus({ preventScroll: true }); } catch (err) { knob.focus(); } }
      drag = { y: e.clientY, acc: 0, moved: 0 };
    });
    knob.addEventListener("pointermove", function (e) {
      if (!drag) return;
      var dy = drag.y - e.clientY;
      drag.y = e.clientY; drag.acc += dy; drag.moved += Math.abs(dy);
      while (drag.acc >= PX_PER_DETENT) { turn(1, e.shiftKey); drag.acc -= PX_PER_DETENT; }
      while (drag.acc <= -PX_PER_DETENT) { turn(-1, e.shiftKey); drag.acc += PX_PER_DETENT; }
    });
    function end(e) {
      if (!drag) return;
      if (drag.moved < 4 && e.pointerType !== "mouse") {
        var now = Date.now();
        if (now - lastTap < 320) { reset(); lastTap = 0; } else lastTap = now;
      }
      drag = null;
    }
    knob.addEventListener("pointerup", end);
    knob.addEventListener("pointercancel", end);
    knob.addEventListener("dblclick", function (e) { e.preventDefault(); reset(); });
    var wheel = 0;
    knob.addEventListener("wheel", function (e) {
      e.preventDefault();
      wheel += e.deltaMode === 1 ? e.deltaY * 16 : e.deltaY;
      while (wheel <= -WHEEL_PER_DETENT) { turn(1, e.shiftKey); wheel += WHEEL_PER_DETENT; }
      while (wheel >= WHEEL_PER_DETENT) { turn(-1, e.shiftKey); wheel -= WHEEL_PER_DETENT; }
    }, { passive: false });
    knob.addEventListener("keydown", function (e) {
      var k = e.key, fine = e.shiftKey;
      if (k === "ArrowUp" || k === "ArrowRight") turn(1, fine);
      else if (k === "ArrowDown" || k === "ArrowLeft") turn(-1, fine);
      else if (k === "PageUp") { for (var i = 0; i < 8; i++) turn(1, fine); }
      else if (k === "PageDown") { for (var j = 0; j < 8; j++) turn(-1, fine); }
      else if (k === "Home") { state.value = min; render(); }
      else if (k === "End") { state.value = max; render(); }
      else if (k === "Delete" || k === "Backspace" || k === "0") reset();
      else return;
      e.preventDefault();
    });
    render();
  }

  function build(root) {
    var sw = DATA.strip[0], sh = DATA.strip[1];
    var W = DATA.pitch * (DATA.strips - 1) + sw;
    var svg = el("svg", { viewBox: "-1.5 -1.5 " + (W + 3) + " " + (sh + 3), "class": "surface__svg",
                          role: "group", "aria-label": "Control surface, four channel strips, seen from above" });
    defs(svg);
    var resets = [];
    for (var s = 0; s < DATA.strips; s++) {
      var g = el("g", { transform: "translate(" + (s * DATA.pitch) + " 0)" }, svg);
      el("path", { d: DATA.outline, "class": "sf-panel" }, g);
      // silkscreen (tools/faceplate-silkscreen.svg): white labels, white boxes with dark labels, outlined boxes
      DATA.silk.boxes.forEach(function (b) {
        el("rect", { x: b[0], y: b[1], width: b[2], height: b[3], rx: b[4],
                     "class": b[5] === "fill" ? "sf-silk-box" : "sf-silk-outline", "stroke-width": b[5] === "fill" ? null : b[6] }, g);
      });
      DATA.silk.texts.forEach(function (t) {
        var tx = el("text", { x: t[0], y: t[1], "font-size": t[2], "class": t[3] === "grey" ? "sf-silk-text sf-silk-dark" : "sf-silk-text" }, g);
        tx.textContent = t[4];
      });
      DATA.screws.forEach(function (c) {
        el("circle", { cx: c[0], cy: c[1], r: c[2], "class": "sf-hole" }, g);
        el("circle", { cx: c[0], cy: c[1], r: (c[2] * 0.62).toFixed(2), "class": "sf-screw" }, g);
      });
      // screen
      el("path", { d: DATA.display.d, "class": "sf-screen" }, g);
      var label = el("text", { x: (DATA.display.x + 1.6).toFixed(2), y: (DATA.display.y + 4.2).toFixed(2), "class": "sf-screen-text" }, g);
      label.textContent = "0" + (s + 1);
      // fader slot and cap
      el("path", { d: DATA.fader, "class": "sf-hole" }, g);
      var fy = sh - (86 + (DATA.faderTravel[s] - 0.5) * 100);
      el("rect", { x: (DATA.faderX - 4.5).toFixed(2), y: (fy - 10).toFixed(2), width: "9", height: "20", rx: "0.8",
                   fill: "url(#sf-fader)", "class": "sf-fadercap" }, g);
      // status LEDs and buttons (not interactive yet)
      DATA.leds.forEach(function (c) {
        el("circle", { cx: c[0], cy: c[1], r: "1.6", "class": "sf-hole" }, g);
        el("circle", { cx: c[0], cy: c[1], r: "1.4", "class": "sf-statusled" }, g);
      });
      DATA.buttons.forEach(function (b) {
        el("path", { d: b.d, "class": "sf-hole" }, g);
        var w = b.kind === "big" ? 6 : 4;
        el("rect", { x: (b.x - w / 2).toFixed(2), y: (b.y - w / 2).toFixed(2), width: w, height: w, rx: b.kind === "big" ? "0.6" : "0.4",
                     "class": b.kind === "big" ? "sf-cap-big" : "sf-cap-small" }, g);
      });
      for (var k = 0; k < DATA.encoders.length; k++) addKnob(g, s, k, DATA.encoders[k][0], DATA.encoders[k][1], resets);
    }
    root.appendChild(svg);
    var btn = root.parentNode && root.parentNode.querySelector("[data-surface-reset]");
    if (btn) {
      btn.hidden = false;
      btn.addEventListener("click", function () { resets.forEach(function (r) { r(); }); });
    }
  }

  function init() {
    var roots = document.querySelectorAll("[data-surface]");
    for (var i = 0; i < roots.length; i++) build(roots[i]);
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
})();
